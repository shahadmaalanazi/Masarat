def normalize_match_id(match_id):
    value = str(match_id or "").strip().upper()
    if value.isdigit():
        return f"M{int(value):03d}"
    if value.startswith("MATCH_") and value[6:].isdigit():
        return f"M{int(value[6:]):03d}"
    if value.startswith("M") and value[1:].isdigit():
        return f"M{int(value[1:]):03d}"
    return value


def get_match(match_id):
    record = MATCHES_BY_ID.get(normalize_match_id(match_id))
    return deepcopy(record) if record is not None else None


